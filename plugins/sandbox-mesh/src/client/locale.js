export function normalizeLang(rawLocale) {
  const str = String(rawLocale || '').toLowerCase()
  return str.startsWith('zh') ? 'zh' : 'en'
}

export function createTranslator(rawLocale) {
  const lang = normalizeLang(rawLocale)
  const dict = lang === 'zh' ? zh : en
  return (key) => dict[key] ?? en[key] ?? key
}
